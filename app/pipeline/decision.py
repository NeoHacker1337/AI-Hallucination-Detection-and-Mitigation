"""Stage 7: confidence and decision logic (pure functions, fully unit-tested).

Rules, applied in order:
1. The answer itself is an abstention                          -> UNCERTAIN
2. Query is ambiguous and clarification is enabled              -> UNCERTAIN (ask to clarify)
3. Contradicted-claim fraction >= contradicted_fail             -> FAILED
3b. A type-specific check found a hard issue (fabricated citation,
    wrong arithmetic, invalid code, self-contradiction; C6 only)  -> FAILED
4. SelfCheck score >= selfcheck_fail                            -> FAILED
5. Normalised semantic entropy >= entropy_uncertain             -> UNCERTAIN
6. Supported-claim fraction < min_supported                     -> UNCERTAIN (not enough evidence)
7. Confidence >= verified_confidence (+ margin if high risk)    -> VERIFIED, else UNCERTAIN

FAILED answers are regenerated by the orchestrator up to R times and then become NEEDS_REVIEW.
Confidence is the mean of the available components: 1 - SE_norm, 1 - SelfCheck, supported fraction.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum

from app.pipeline.settings import Thresholds


class Decision(str, Enum):
    """Possible outcomes of the decision stage."""

    VERIFIED = "VERIFIED"
    UNCERTAIN = "UNCERTAIN"
    FAILED = "FAILED"
    NEEDS_REVIEW = "NEEDS_REVIEW"
    UNCHECKED = "UNCHECKED"  # decision stage disabled


@dataclass
class Signals:
    """Detector outputs fed into the decision."""

    semantic_entropy_norm: float | None = None
    selfcheck_score: float | None = None
    supported_fraction: float | None = None
    contradicted_fraction: float | None = None
    answer_is_abstention: bool = False
    ambiguous: bool = False
    ambiguity_reason: str | None = None
    high_risk: bool = False
    hard_issues: list[str] | None = None  # from type-specific checks (None when they did not run)

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class DecisionResult:
    """Decision, confidence and the reasons that led to it."""

    decision: Decision
    confidence: float | None
    reasons: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {"decision": self.decision.value, "confidence": self.confidence, "reasons": self.reasons}


def compute_confidence(signals: Signals) -> float | None:
    """Mean of available confidence components; None when no detector ran."""
    parts: list[float] = []
    if signals.semantic_entropy_norm is not None:
        parts.append(1.0 - signals.semantic_entropy_norm)
    if signals.selfcheck_score is not None:
        parts.append(1.0 - signals.selfcheck_score)
    if signals.supported_fraction is not None:
        parts.append(signals.supported_fraction)
    if not parts:
        return None
    return float(min(max(sum(parts) / len(parts), 0.0), 1.0))


def decide(signals: Signals, thresholds: Thresholds, ask_clarification: bool = True) -> DecisionResult:
    """Apply the decision rules documented in the module docstring."""
    confidence = compute_confidence(signals)
    if signals.answer_is_abstention:
        return DecisionResult(Decision.UNCERTAIN, confidence, ["model abstained"])
    if signals.ambiguous and ask_clarification:
        reason = signals.ambiguity_reason or "query is ambiguous"
        return DecisionResult(Decision.UNCERTAIN, confidence, [f"ambiguous query: {reason}"])
    if signals.contradicted_fraction is not None and signals.contradicted_fraction >= thresholds.contradicted_fail:
        return DecisionResult(
            Decision.FAILED, confidence,
            [f"contradicted fraction {signals.contradicted_fraction:.2f} >= {thresholds.contradicted_fail}"],
        )
    if signals.hard_issues:
        return DecisionResult(Decision.FAILED, confidence, [f"type check failed: {i}" for i in signals.hard_issues])
    if signals.selfcheck_score is not None and signals.selfcheck_score >= thresholds.selfcheck_fail:
        return DecisionResult(
            Decision.FAILED, confidence,
            [f"self-check score {signals.selfcheck_score:.2f} >= {thresholds.selfcheck_fail}"],
        )
    if signals.semantic_entropy_norm is not None and signals.semantic_entropy_norm >= thresholds.entropy_uncertain:
        return DecisionResult(
            Decision.UNCERTAIN, confidence,
            [f"semantic entropy {signals.semantic_entropy_norm:.2f} >= {thresholds.entropy_uncertain}"],
        )
    if signals.supported_fraction is not None and signals.supported_fraction < thresholds.min_supported:
        return DecisionResult(
            Decision.UNCERTAIN, confidence,
            [f"supported fraction {signals.supported_fraction:.2f} < {thresholds.min_supported}"],
        )
    if confidence is None:
        return DecisionResult(Decision.VERIFIED, None, ["no detector signals; passed by default"])
    required = thresholds.verified_confidence + (thresholds.high_risk_margin if signals.high_risk else 0.0)
    required = min(required, 1.0)
    if confidence >= required:
        return DecisionResult(Decision.VERIFIED, confidence, [f"confidence {confidence:.2f} >= {required:.2f}"])
    return DecisionResult(
        Decision.UNCERTAIN, confidence,
        [f"confidence {confidence:.2f} < {required:.2f}" + (" (high-risk query)" if signals.high_risk else "")],
    )


def is_flagged(decision: Decision) -> bool:
    """True when the detector flags the answer as a (potential) hallucination."""
    return decision in (Decision.FAILED, Decision.UNCERTAIN, Decision.NEEDS_REVIEW)
